        ph_a = Article.objects.filter(title__icontains="(пример)").update(is_published=False)
        self.stdout.write(f"Скрыто заглушек: кейсов {ph_p}, статей {ph_a}")

        # Ссылка на услугу АСУ ТП для перелинковки (если услуга есть).
        svc = Service.objects.filter(direction="automation", is_active=True).first()
        service_url = svc.get_absolute_url() if svc else reverse("content:hub")
        projects_url = reverse("content:project_list")

        # 2. Кейсы.
        for data in PROJECTS:
            slug = data["slug"]
            defaults = {k: v for k, v in data.items() if k != "slug"}
            defaults["direction"] = "automation"
            defaults["is_published"] = True
            obj, created = Project.objects.update_or_create(slug=slug, defaults=defaults)
            self.stdout.write(("＋ создан" if created else "↻ обновлён") + f" кейс: {obj.title}")

