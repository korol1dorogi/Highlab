class Command(BaseCommand):
    help = "Наполняет блог полезными статьями под информационные запросы."

    def handle(self, *args, **options):
        for data in ARTICLES:
            slug = data["slug"]
            defaults = {k: v for k, v in data.items() if k != "slug"}
            defaults["is_published"] = True
            obj, created = Article.objects.update_or_create(slug=slug, defaults=defaults)
            self.stdout.write(("＋ создана" if created else "↻ обновлена") + f" статья: {obj.title}")
        self.stdout.write(self.style.SUCCESS(f"Готово: статей загружено — {len(ARTICLES)}."))
