class Command(BaseCommand):
    help = "Создаёт/обновляет посадочные страницы под Яндекс.Директ."

    def handle(self, *args, **options):
        for spec in LANDINGS:
            obj, created = Landing.objects.update_or_create(
                slug=spec["slug"],
                defaults={k: v for k, v in spec.items() if k != "slug"} | {"is_active": True},
            )
            flag = "создана" if created else "обновлена"
            self.stdout.write(self.style.SUCCESS(f"/lp/{obj.slug}/ — {flag}: {obj.title}"))

        self.stdout.write(self.style.SUCCESS(
            f"Активных посадочных: {Landing.objects.filter(is_active=True).count()}"
        ))
